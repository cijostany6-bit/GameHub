#!/bin/bash
# =========================================================
# GameHub — build the deployable static artifact.
#
# Copies frontend/ into build/frontend/ (git-ignored) and writes
# the runtime config from the environment. The committed
# frontend/config.js stays in local-development mode, so a deploy
# can never "leak" pool settings into the repository.
#
# Requires: COGNITO_REGION, COGNITO_USER_POOL_ID, COGNITO_CLIENT_ID
# =========================================================

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD="$ROOT/build/frontend"

: "${COGNITO_REGION:?COGNITO_REGION is required}"
: "${COGNITO_USER_POOL_ID:?COGNITO_USER_POOL_ID is required}"
: "${COGNITO_CLIENT_ID:?COGNITO_CLIENT_ID is required}"

rm -rf "$BUILD"
mkdir -p "$BUILD"
cp -R "$ROOT/frontend/." "$BUILD/"

# Tests and the nginx config are development-only.
rm -rf "$BUILD/test" "$BUILD/nginx.conf"

cat > "$BUILD/config.js" <<EOF
"use strict";

/* Generated by scripts/build-frontend.sh for this deployment.
   Local development uses the committed config.js (authEnabled:false). */

window.GAMEHUB_CONFIG = {
    authEnabled: true,
    region: "${COGNITO_REGION}",
    userPoolId: "${COGNITO_USER_POOL_ID}",
    clientId: "${COGNITO_CLIENT_ID}",
    apiBase: ""
};
EOF

echo "Built $BUILD"
